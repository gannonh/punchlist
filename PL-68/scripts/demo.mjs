// A paced walkthrough of the Pull requests page on the pl68-branch run, recorded as video.
import { execFileSync } from 'node:child_process'
import { chromium } from '/home/gannonh/.local/share/punchlist/worktrees/worktrees/gannonh/punchlist/PL-68/node_modules/.pnpm/node_modules/playwright/index.mjs'

const OUT = '/home/gannonh/.cache/pl68-live/video'
const sh = (cmd) => execFileSync('bash', ['-c', `source ~/.cache/pl68-live/env.sh >/dev/null; ${cmd}`], { encoding: 'utf8' })
const pause = (ms = 2500) => new Promise((r) => setTimeout(r, ms))
const signIn = sh('$C sign-in-url "$RUN"').trim()
const browser = await chromium.launch()
const context = await browser.newContext({ viewport: { width: 1280, height: 800 }, recordVideo: { dir: OUT, size: { width: 1280, height: 800 } } })
const page = await context.newPage()
const row = (n) => page.locator(`[data-pr-row="${String(n)}"]`)

await page.goto(signIn)
await page.waitForURL((u) => u.pathname === '/')
await page.locator('[data-pull-request-count]').waitFor()
await pause(3000)
await page.keyboard.press('g')
await page.keyboard.press('p')
await page.locator('[data-section]').first().waitFor()
await pause(3500)

sh('pr ready_for_review pull_request_ready_for_review 8 feature/pl-2-b $(sha 8) "Live two" false')
await page.locator('[data-section="in-review"] [data-pr-row="8"]').waitFor()
await row(8).hover()
await pause(3500)

sh(`$C sql "$RUN" "UPDATE issue SET status = 'merging' WHERE id = 'PL-3'"`)
sh('pr opened pull_request_opened 15 feature/pl-3-e $(sha 15) "Live three, again" false')
await page.locator('[data-section="waits-on-merge"] [data-pr-row="15"]').waitFor()
await row(15).locator('a', { hasText: 'Merge on GitHub' }).hover()
await pause(4000)
sh('pr closed pull_request_closed_merged 15 feature/pl-3-e $(sha 15) "Live three, again" false')
await row(15).waitFor({ state: 'detached' })
await pause(3500)

await row(7).focus()
await pause(1500)
await page.keyboard.press('Enter')
await page.waitForURL((u) => u.pathname === '/issues/PL-1')
await pause(3500)
await page.keyboard.press('Escape')
await page.waitForURL((u) => u.pathname === '/')
await pause(2500)
await page.getByRole('link', { name: /Pull requests/ }).click()
await page.locator('[data-section]').first().waitFor()
await pause(2500)
await page.setViewportSize({ width: 390, height: 844 })
await pause(3000)
await page.mouse.wheel(0, 600)
await pause(3000)
await context.close()
await browser.close()
console.log(sh(`$C sql "$RUN" "SELECT id, status FROM issue WHERE id = 'PL-3'"`))
